#!/usr/bin/env node
/* ------------------------------------------------------------------
   Build: src/ + assets/  ->  "Alpha Premier ID Maker.html"
   ------------------------------------------------------------------
   Inlines every local stylesheet and script from src/index.html and
   replaces assets.dev.js with base64 data: URLs, so the output is ONE
   file that works offline from a double-click.

     node build.mjs

   No dependencies. Node 18 or newer.
   ------------------------------------------------------------------ */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, 'src');
const out = join(root, 'Alpha Premier ID Maker.html');

const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.woff2': 'font/woff2' };
const dataUrl = (rel) => {
  const file = resolve(src, rel);
  const mime = MIME[extname(file).toLowerCase()];
  if (!mime) throw new Error(`No MIME type for ${rel}`);
  return `data:${mime};base64,${readFileSync(file).toString('base64')}`;
};

// 1. the asset table: evaluate assets.dev.js and swap each path for a data URL
const assetsSrc = readFileSync(join(src, 'assets.dev.js'), 'utf8');
const devAssets = new Function(`${assetsSrc}; return ASSETS;`)();
const built = {
  front: dataUrl(devAssets.front),
  back: dataUrl(devAssets.back),
  example: dataUrl(devAssets.example),
  fonts: Object.fromEntries(Object.entries(devAssets.fonts).map(([k, pair]) => [k, pair.map(dataUrl)])),
};
const assetsJs = `/* generated by build.mjs — edit assets.dev.js, not this */\nconst ASSETS = ${JSON.stringify(built)};`;

// 2. walk src/index.html and inline
let html = readFileSync(join(src, 'index.html'), 'utf8');
html = html.replace(/<!--[\s\S]*?-->\n?/g, (c) => (c.includes('Development page') ? '' : c));   // drop the dev note

html = html.replace(/<link rel="stylesheet" href="([^"]+)" \/>/g, (tag, href) => {
  if (/^https?:/.test(href)) return tag;
  return `<style>\n${readFileSync(join(src, href), 'utf8')}\n</style>`;
});

html = html.replace(/<script src="([^"]+)"><\/script>/g, (tag, file) => {
  const body = file === 'assets.dev.js' ? assetsJs : readFileSync(join(src, file), 'utf8');
  return `<script>\n${body.replace(/<\/script/gi, '<\\/script')}\n</script>`;
});

writeFileSync(out, html);
console.log(`wrote ${out} (${(statSync(out).size / 1024 / 1024).toFixed(2)} MB)`);
